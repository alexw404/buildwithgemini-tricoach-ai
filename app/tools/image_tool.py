"""Image generation tool for TriCoach AI using gemini-3.1-flash-lite-image."""

import time
from typing import Any, Dict
from google.adk.tools.tool_context import ToolContext
from google.cloud import storage
from google.genai import Client, types

BUCKET_NAME = "tricoach-ai-media-57b0d8b0ef08"
PROJECT_ID = "qwiklabs-gcp-01-57b0d8b0ef08"


async def generate_triathlon_badge_image(
    prompt: str, tool_context: ToolContext
) -> Dict[str, Any]:
    """Generate a motivational triathlon achievement badge or workout graphic.

    Args:
        prompt: Description of the graphic or badge to generate (e.g. 'A futuristic triathlon finish line badge with swim, bike, run icons').

    Returns:
        Dictionary with public image URL and metadata.
    """
    try:
        # Initialize GenAI Client with Vertex AI in global region
        genai_client = Client(
            vertexai=True, project=PROJECT_ID, location="global"
        )

        response = genai_client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=prompt,
        )

        image_bytes = None
        mime_type = "image/jpeg"

        if response.candidates:
            for candidate in response.candidates:
                if candidate.content and candidate.content.parts:
                    for part in candidate.content.parts:
                        if part.inline_data:
                            image_bytes = part.inline_data.data
                            mime_type = (
                                part.inline_data.mime_type or "image/jpeg"
                            )
                            break
                if image_bytes:
                    break

        if not image_bytes:
            return {"error": "No image data was generated by the model."}

        # 1. Save artifact for Playground
        filename = f"badge_{int(time.time())}.jpg"
        artifact_part = types.Part.from_bytes(
            data=image_bytes, mime_type=mime_type
        )
        await tool_context.save_artifact(
            filename=filename, artifact=artifact_part
        )

        # 2. Upload image bytes directly to public GCS bucket (no local file)
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        object_key = f"badges/{filename}"
        blob = bucket.blob(object_key)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = (
            f"https://storage.googleapis.com/{BUCKET_NAME}/{object_key}"
        )

        return {
            "status": "success",
            "public_url": public_url,
            "filename": filename,
            "message": f"Generated image and uploaded to {public_url}",
        }
    except Exception as e:
        return {"error": f"Failed to generate image: {str(e)}"}
