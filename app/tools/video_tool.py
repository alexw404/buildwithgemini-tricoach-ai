"""Video generation tool for TriCoach AI using gemini-omni-flash-preview."""

import base64
import time
from typing import Any, Dict
from google.adk.tools.tool_context import ToolContext
from google.cloud import storage
from google.genai import Client, types

BUCKET_NAME = "tricoach-ai-media-57b0d8b0ef08"
PROJECT_ID = "qwiklabs-gcp-01-57b0d8b0ef08"


async def generate_triathlon_video(
    prompt: str, tool_context: ToolContext
) -> Dict[str, Any]:
    """Generate a short triathlon training video clip (e.g. swim, bike, run technique or motivation).

    Args:
        prompt: Description of the video clip to generate (e.g. 'A triathlete sprinting towards the finish line in slow motion').

    Returns:
        Dictionary with public video URL and metadata.
    """
    try:
        # Initialize GenAI Client with Vertex AI in global region
        genai_client = Client(
            vertexai=True, project=PROJECT_ID, location="global"
        )

        response = genai_client.interactions.create(
            model="gemini-omni-flash-preview",
            input=prompt,
        )

        video_bytes = None
        mime_type = "video/mp4"

        if response.output_video and response.output_video.data:
            data_val = response.output_video.data
            if isinstance(data_val, str):
                video_bytes = base64.b64decode(data_val)
            else:
                video_bytes = data_val
            if hasattr(response.output_video, "mime_type") and response.output_video.mime_type:
                mime_type = response.output_video.mime_type

        if not video_bytes:
            return {"error": "No video data was generated by the model."}

        # 1. Save artifact for Playground
        filename = f"triathlon_video_{int(time.time())}.mp4"
        artifact_part = types.Part.from_bytes(
            data=video_bytes, mime_type=mime_type
        )
        await tool_context.save_artifact(
            filename=filename, artifact=artifact_part
        )

        # 2. Upload video bytes directly to public GCS bucket (no local file)
        storage_client = storage.Client(project=PROJECT_ID)
        bucket = storage_client.bucket(BUCKET_NAME)
        object_key = f"videos/{filename}"
        blob = bucket.blob(object_key)
        blob.upload_from_string(video_bytes, content_type=mime_type)

        public_url = (
            f"https://storage.googleapis.com/{BUCKET_NAME}/{object_key}"
        )

        return {
            "status": "success",
            "public_url": public_url,
            "filename": filename,
            "message": f"Generated video and uploaded to {public_url}",
        }
    except Exception as e:
        return {"error": f"Failed to generate video: {str(e)}"}
